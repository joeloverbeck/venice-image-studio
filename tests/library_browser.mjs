import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({executablePath: process.env.CHROME_BIN || '/usr/bin/google-chrome', args: ['--no-sandbox']});
const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(process.env.STUDIO_URL);
  await page.locator('#library-search').fill('absent result');
  await page.getByText('No attempts match this search.').waitFor();
  assert.equal(await page.locator('#prompt').inputValue(), 'Unfinished draft stays here');
  await page.locator('#prompt').fill('Draft kept through navigation 🦊');
  await page.locator('#safe').check();
  await page.locator('#setting-width').fill('768');
  await page.locator('#setting-width').blur();
  await page.getByText('Draft saved locally.', {exact: true}).waitFor();
  await page.locator('#browse-models').click();
  await page.locator('#close-models').click();
  await page.locator('#library-search').fill('CHROMA');
  await page.locator(`[data-attempt="${process.env.ATTEMPT_ID}"]`).click();
  assert.equal(await page.locator('#prompt').inputValue(), 'Draft kept through navigation 🦊');
  assert.equal(await page.locator('#setting-width').inputValue(), '768');
  assert.equal(await page.locator('#safe').isChecked(), true);
  await page.getByRole('button', {name: 'Inspect original', exact: true}).click();
  await page.locator('#original-inspector[open]').waitFor();
  await page.getByRole('button', {name: '100%', exact: true}).click();
  await page.waitForFunction(() => document.querySelector('#inspector-image').getBoundingClientRect().width === 2048);
  const before = await page.locator('#inspector-image').getAttribute('style');
  const viewport = await page.locator('#inspector-viewport').boundingBox();
  await page.mouse.move(viewport.x + viewport.width / 2, viewport.y + viewport.height / 2);
  await page.mouse.down(); await page.mouse.move(viewport.x + viewport.width / 2 + 120, viewport.y + viewport.height / 2 + 50); await page.mouse.up();
  assert.notEqual(await page.locator('#inspector-image').getAttribute('style'), before);
  await page.getByRole('button', {name: 'Zoom in', exact: true}).click();
  await page.waitForFunction(() => document.querySelector('#inspector-image').getBoundingClientRect().width > 2048);
  await page.getByRole('button', {name: 'Fit to view', exact: true}).click();
  await page.waitForFunction(() => document.querySelector('#inspector-image').getBoundingClientRect().width <= document.querySelector('#inspector-viewport').clientWidth);
  await page.getByRole('button', {name: 'Fullscreen', exact: true}).click();
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  await page.getByRole('button', {name: 'Exit fullscreen', exact: true}).click();
  await page.waitForFunction(() => !document.fullscreenElement);
  await page.locator('#close-inspector').click();
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#images').getByRole('link', {name: 'Download original'}).click();
  const download = await downloadEvent;
  assert.equal(createHash('sha256').update(await readFile(await download.path())).digest('hex'), process.env.ORIGINAL_SHA256);
  const recipeEvent = page.waitForEvent('download');
  await page.getByRole('link', {name: 'Export recipe JSON', exact: true}).click();
  const recipe = JSON.parse(await readFile(await (await recipeEvent).path(), 'utf8'));
  assert.equal(recipe.prompt, 'Amber original <script>window.unsafe=true</script> 🦊');
  assert.equal(recipe.provider, undefined);
  assert.equal(JSON.stringify(recipe).includes('PRIVATE DIAGNOSTIC MARKER'), false);
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#prompt').value === 'Draft kept through navigation 🦊');
  assert.equal(await page.locator('#setting-width').inputValue(), '768');
  assert.equal(await page.locator('#safe').isChecked(), true);
  await page.getByRole('button', {name: 'Use recipe as new draft', exact: true}).click();
  await page.getByText('New draft saved. Nothing has been generated.', {exact: true}).waitFor();
  assert.equal(await page.locator('#prompt').inputValue(), recipe.prompt);
  assert.match(await page.locator('#preflight').innerText(), /unavailable/);
  assert.equal(await page.locator('#generate').isDisabled(), true);
  assert.equal(await page.evaluate(() => window.unsafe), undefined);
  assert.deepEqual(errors, []);
  console.log('PASS: browser search, no match, draft navigation/reload, original fit/100%/pan/zoom/fullscreen, exact download, separate recipe export and removed-model reuse.');
} finally { await browser.close(); }
